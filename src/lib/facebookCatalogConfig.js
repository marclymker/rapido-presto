// Fonction pour obtenir toutes les sous-catégories Facebook de manière aplatie
export const getAllFacebookSubcategories = () => {
  const all = [];
  Object.values(FACEBOOK_CATEGORIES_COMPLETE).forEach(category => {
    all.push(...(category.subcategories || []));
  });
  return all;
};

// Fonction pour trouver la catégorie parente d'une sous-catégorie
export const getFacebookCategoryParent = (subcategoryPath) => {
  for (const [parentKey, parentData] of Object.entries(FACEBOOK_CATEGORIES_COMPLETE)) {
    if (parentData.subcategories?.includes(subcategoryPath)) {
      return { key: parentKey, label: parentData.label, icon: parentData.icon };
    }
  }
  return null;
};